#[cfg(test)]
mod tests {
    use crate::geo::NATIONS;
    use crate::lang::has;
    use crate::world::*;

    /// データに出てくる日本語はすべて辞書に訳がある
    #[test]
    fn dict_covers_data() {
        let mut all: Vec<&'static str> = Vec::new();
        let mut need = |s: &'static str| all.push(s);
        for d in NATIONS.iter() {
            need(d.name);
            need(d.desc);
        }
        need("天使");
        for d in NATIONS.iter() {
            for c in d.cities {
                need(c.name);
            }
        }
        for h in INITIAL_HOUSE {
            need(h);
        }
        for e in HISTORY {
            need(e.title);
            need(e.text);
            for fx in e.fx {
                match fx {
                    Fx::Figure(n, ..) | Fx::Dismiss(n) | Fx::House(n) => need(n),
                    _ => {}
                }
            }
        }
        for t in TRAITS {
            need(t.name);
            need(t.desc);
        }
        for c in CONVOYS {
            need(c.name);
        }
        let mut missing: Vec<&str> = all.into_iter().filter(|s| !has(s)).collect();
        missing.dedup();
        assert!(missing.is_empty(), "辞書に無い：{:?}", missing);
    }
}
