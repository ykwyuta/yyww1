//!
//! 舞台は1914年の欧州：大西洋・北米の東海岸・トルコ（小アジアと中東）・ウラル山脈まで。
//! 大西洋の中ほどは経度方向に縮めて描く（区分ごとの線形の投影）。

use crate::rng::{fbm, hash2, Rng};

/// 緯度1度あたりのタイル数
const TPD_Y: f32 = 11.0;
/// 経度1度あたりのタイル数（欧州・北米）
const TPD_X: f32 = 7.2;
/// 大西洋の中ほどを縮める率
const ATL: f32 = 0.25;
/// 地図の西端・大西洋の始まり・終わり・東端（経度）
pub const LON0: f32 = -78.5;
const LON_A: f32 = -62.0;
const LON_B: f32 = -13.0;
#[allow(dead_code)]
pub const LON1: f32 = 62.0;
pub const LAT_TOP: f32 = 65.0;
#[allow(dead_code)]
pub const LAT_BOT: f32 = 29.5;

pub const MAP_W: usize = 748;
pub const MAP_H: usize = 390;

pub fn ll_to_tile(lon: f32, lat: f32) -> (f32, f32) {
    let wa = (LON_A - LON0) * TPD_X;
    let wb = (LON_B - LON_A) * TPD_X * ATL;
    let x = if lon <= LON_A {
        (lon - LON0) * TPD_X
    } else if lon <= LON_B {
        wa + (lon - LON_A) * TPD_X * ATL
    } else {
        wa + wb + (lon - LON_B) * TPD_X
    };
    (x, (LAT_TOP - lat) * TPD_Y)
}

pub fn tile_to_ll(x: f32, y: f32) -> (f32, f32) {
    let wa = (LON_A - LON0) * TPD_X;
    let wb = (LON_B - LON_A) * TPD_X * ATL;
    let lon = if x <= wa {
        LON0 + x / TPD_X
    } else if x <= wa + wb {
        LON_A + (x - wa) / (TPD_X * ATL)
    } else {
        LON_B + (x - wa - wb) / TPD_X
    };
    (lon, LAT_TOP - y / TPD_Y)
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Terrain {
    Sea,
    Lake,
    River,
    Plain,
    Steppe,
    Forest,
    Hill,
    Mountain,
    /// 砂漠（北アフリカ・中東）
    Desert,
}

impl Terrain {
    pub fn passable(self) -> bool {
        !matches!(self, Terrain::Sea | Terrain::Lake | Terrain::Mountain)
    }
    pub fn move_cost(self) -> f32 {
        match self {
            Terrain::Plain | Terrain::Steppe => 1.0,
            Terrain::Desert => 1.3,
            Terrain::Forest => 1.6,
            Terrain::Hill => 1.5,
            Terrain::River => 2.5,
            _ => f32::INFINITY,
        }
    }
    /// 建物を置ける地形
    pub fn buildable(self) -> bool {
        matches!(self, Terrain::Plain | Terrain::Steppe | Terrain::Hill | Terrain::Desert)
    }
    /// 船が通れる
    pub fn navigable(self) -> bool {
        self == Terrain::Sea
    }
}

